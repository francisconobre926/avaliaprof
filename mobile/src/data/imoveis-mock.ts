// Função auxiliar para formatar preços
export const formatarPreco = (preco: number, periodicidade?: string): string => {
  const formatado = new Intl.NumberFormat('pt-PT', {
    minimumFractionDigits: 0,
    maximumFractionDigits: 0,
  }).format(preco);

  const sufixo = periodicidade === 'mensal' ? '/mês' : '';
  return `${formatado} MT${sufixo}`;
};

// Função auxiliar para tempo desde publicação
export const tempoDesdeMock = (data: string): string => {
  const publicado = new Date(data);
  const agora = new Date('2026-09-11');
  const diffMs = agora.getTime() - publicado.getTime();
  const diffDias = Math.floor(diffMs / (1000 * 60 * 60 * 24));

  if (diffDias === 0) return 'Hoje';
  if (diffDias === 1) return 'Ontem';
  if (diffDias < 7) return `Há ${diffDias} dias`;
  if (diffDias < 30) return `Há ${Math.floor(diffDias / 7)} semanas`;
  return `Há ${Math.floor(diffDias / 30)} meses`;
};