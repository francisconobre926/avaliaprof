const avisados = new Set<string>();

export function nomeIonicons(nome: string): keyof typeof Ionicons.glyphMap | null {
  if (nome in Ionicons.glyphMap) return nome as keyof typeof Ionicons.glyphMap;
  return MCI_PARA_IONICONS[nome] ?? null;
}

export default function Icone({ name, ...props }: IconeProps) {
  const ion = nomeIonicons(name);
  if (ion) return <Ionicons name={ion} {...props} />;

  // Sem equivalente mapeado: não parte o ecrã, mas avisa em desenvolvimento.
  if (__DEV__ && !avisados.has(name)) {
    avisados.add(name);
    console.warn(`[Icone] sem equivalente Ionicons para "${name}" — adiciona-o ao mapa em Icone.tsx`);
  }
  return <MaterialCommunityIcons name={name as any} {...(props as any)} />;
}
